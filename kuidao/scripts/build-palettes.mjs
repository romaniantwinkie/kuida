// Generates src/app/palettes.css from src/lib/palettes.json and checks contrast.
// Run: node scripts/build-palettes.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(new URL("../src/lib/palettes.json", import.meta.url)));
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");
const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const vars = (tokens, scheme) =>
  Object.entries({ ...tokens, ...src.shared[scheme] })
    .map(([k, v]) => `  --${k}: ${rgb(v)};`)
    .join("\n") + `\n  color-scheme: ${scheme};`;

let css = "/* GENERATED by scripts/build-palettes.mjs from src/lib/palettes.json. Do not edit. */\n";
css += "/* Selectors use :where() (zero specificity) so source order decides: light < system-dark < forced-dark < forced-light. */\n";
const problems = [];
for (const p of src.palettes) {
  const P = `[data-palette="${p.id}"]`;
  css += `\n/* ${p.name} */\n`;
  css += `:where(${P}) {\n${vars(p.light, "light")}\n}\n`;
  css += `@media (prefers-color-scheme: dark) {\n  :where(:root:not([data-theme="light"])) :where(${P}), :where(:root:not([data-theme="light"])${P}) {\n${vars(p.dark, "dark").replace(/^/gm, "  ")}\n  }\n}\n`;
  css += `:where([data-theme="dark"]) :where(${P}), :where([data-theme="dark"]${P}) {\n${vars(p.dark, "dark")}\n}\n`;
  css += `:where([data-theme="light"]${P}) {\n${vars(p.light, "light")}\n}\n`;

  for (const scheme of ["light", "dark"]) {
    const t = { ...p[scheme], ...src.shared[scheme] };
    const checks = [
      ["brand text on bg", t.brand, t.bg, 4.5],
      ["brand-ink on brand", t["brand-ink"], t.brand, 4.5],
      ["accent-ink on accent", t["accent-ink"], t.accent, 4.5],
      ["accent text on accent-soft", t.accent, t["accent-soft"], 3],
      ["brand text on brand-soft", t.brand, t["brand-soft"], 4.5],
      ["muted on surface", t.muted, t.surface, 4.5],
      ["ink on bg", t.ink, t.bg, 7],
    ];
    for (const [label, fg, bg, min] of checks) {
      const c = contrast(fg, bg);
      if (c < min) problems.push(`${p.id}/${scheme}: ${label} = ${c.toFixed(2)} (< ${min})`);
    }
  }
}
writeFileSync(new URL("../src/app/palettes.css", import.meta.url), css);
console.log(`Wrote ${src.palettes.length} palettes.`);
console.log(problems.length ? "Contrast issues:\n" + problems.join("\n") : "All contrast checks pass.");
process.exitCode = problems.length ? 1 : 0;
